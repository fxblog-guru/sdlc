/**
 * ui-inventory.mjs — the generated component inventory and its second-implementation detectors
 * (DEV-CONTRACTS §13.3). The broken fixture holds one of each duplicate; the valid fixture holds the
 * same screen built from the kit and must be silent.
 *
 *   node --test tests/ui-inventory.test.mjs
 */

import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { copyStrings, cvaVariants, inventory, summary, tagAt } from '../workspace/dev/scripts/ui-inventory.mjs';
import { lintTree, loadTemplates } from '../workspace/dev/scripts/lint-dev.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const FIX = join(here, 'fixtures', 'inventory');
const SCRIPT = join(here, '..', 'workspace', 'dev', 'scripts', 'ui-inventory.mjs');
const run = (args) => spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8' });

test('valid: a screen built from the kit has no second implementation, and the inventory lists its primitives', () => {
  const inv = inventory({ project: join(FIX, 'valid') });
  assert.deepEqual(inv.findings, []);
  assert.deepEqual(inv.primitives.map((p) => p.name).sort(), ['button', 'skeleton']);
  const button = inv.primitives.find((p) => p.name === 'button');
  assert.deepEqual(button.variants, { variant: ['primary', 'danger-outline'] });
  assert.deepEqual(button.consumers.sort(), ['src/features/EditDialog.tsx', 'src/features/ReleasePage.tsx']);
  assert.equal(run(['--project', join(FIX, 'valid')]).status, 0);
});

test('broken: every duplicate role is found once', () => {
  const inv = inventory({ project: join(FIX, 'broken') });
  assert.deepEqual(summary(inv.findings), {
    'class-constant': 1,
    'local-skeleton': 1,
    'badge-function': 1,
    'private-formatter': 2,
    'hand-rolled-menu': 1,
    'raw-button': 1,
    'raw-input': 1,
    'raw-table': 1,
    'copy-object': 2,
    'copy-duplicate': 1,
    'dialog-no-guard': 1,
    'form-validation': 1,
    'static-alert': 1,
    'unmarked-mutation': 1,
  });
  assert.match(inv.findings.find((f) => f.rule === 'copy-duplicate').what, /"Cancel" ×2 in 2 objects/);
});

test('severity is configurable: off drops a rule, warn keeps it without failing', () => {
  const dir = mkdtempSync(join(tmpdir(), 'inv-sev-'));
  const sev = join(dir, 'sev.json');
  const all = ['class-constant', 'local-skeleton', 'badge-function', 'private-formatter', 'hand-rolled-menu', 'raw-button', 'raw-input', 'raw-table', 'copy-duplicate', 'dialog-no-guard', 'form-validation', 'unmarked-mutation'];
  writeFileSync(sev, JSON.stringify(Object.fromEntries(all.map((r) => [r, 'warn']))));
  assert.equal(run(['--project', join(FIX, 'broken'), '--severity', sev]).status, 0, 'all warn: exit 0');
  writeFileSync(sev, JSON.stringify({ 'raw-table': 'off' }));
  const r = JSON.parse(run(['--project', join(FIX, 'broken'), '--severity', sev, '--json']).stdout);
  assert.equal(r.summary['raw-table'], undefined);
  assert.equal(run(['--project', join(FIX, 'broken'), '--severity', sev]).status, 1);
  writeFileSync(sev, JSON.stringify({ 'raw-tables': 'off' }));
  assert.equal(run(['--project', join(FIX, 'broken'), '--severity', sev]).status, 2, 'an unknown rule is a usage error');
});

test('it writes dev/ui/<slug>/components.md, marked generated', () => {
  const dir = mkdtempSync(join(tmpdir(), 'inv-out-'));
  const out = join(dir, 'dev', 'ui', 'demo', 'components.md');
  const r = run(['--project', join(FIX, 'broken'), '--out', out, '--slug', 'demo']);
  assert.equal(r.status, 1);
  const md = readFileSync(out, 'utf8');
  assert.match(md, /^<!-- GENERATED by dev\/scripts\/ui-inventory\.mjs/);
  assert.match(md, /## Primitives[\s\S]*\| `button` \|/);
  assert.match(md, /a private Skeleton \| error \| 1 \| Skeleton \|/);
  // The file is generated and never gated (§2): lint-dev skips it rather than failing E001.
  const findings = lintTree(join(dir, 'dev'), loadTemplates(join(here, '..', 'workspace', 'dev', '_templates')));
  assert.deepEqual(findings.filter((f) => f.file.includes('components.md')), []);
});

test('interaction rules: discard guard, noValidate + ErrorSummary, mutates, role=alert', () => {
  const inv = inventory({ project: join(FIX, 'broken') });
  const on = (rule) => inv.findings.filter((f) => f.rule === rule).map((f) => `${f.file}:${f.line}`);
  assert.deepEqual(on('dialog-no-guard'), ['src/features/EditDialog.tsx:5']);
  assert.deepEqual(on('form-validation'), ['src/features/EditDialog.tsx:6']);
  assert.deepEqual(on('unmarked-mutation'), ['src/features/EditDialog.tsx:8']);
  assert.deepEqual(on('static-alert'), ['src/features/EditDialog.tsx:7']);
});

test('helpers: a tag with an arrow function, copy strings, cva variants', () => {
  assert.equal(tagAt('<button onClick={() => go()} className="x">', 0), '<button onClick={() => go()} className="x">');
  assert.deepEqual(copyStrings("const A_COPY = { a: 'One', b: (n) => `${n} items` };", 0).map((c) => c.value), ['One', '{} items']);
  assert.deepEqual(cvaVariants("cva('x', { variants: { size: { sm: 'h-1', md: 'h-2' } } })"), { size: ['sm', 'md'] });
});
