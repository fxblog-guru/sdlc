/**
 * langs.mjs: the one place that knows about programming languages.
 *
 * Every checker that reads source code asks this registry three questions: which language is this
 * file, is it a test, and how are comments written. Language-specific scanning (limit constants,
 * generated enums) is a capability an adapter offers, not an `if (lang === 'go')` inside a checker.
 *
 * Adding a language is one entry here, plus its `dev-writing-<lang>-code` skill, a blueprint, and a
 * row in DEV-PROFILE §Stacks. tests/langs.test.mjs fails until all four agree. CONTRIBUTING.md
 * "Adding a language" has the steps.
 *
 * An adapter:
 *   id          the language id checkers use ('go', 'python', 'typescript')
 *   stacks      the DEV-PROFILE §Stacks keys it serves (react and nextjs are both typescript)
 *   skill       the implementation skill, per stack key
 *   role        'server' (every file is backend code the API, limits and observability checks read)
 *               or 'client' (none is, unless `isServer` says so)
 *   isServer    optional, client languages only: (posix rel path, text) → is this file backend code
 *               anyway. A full-stack framework keeps its server code beside the UI (Next.js
 *               `src/server/`, route handlers, server actions); the backend checkers read it
 *               through isServerFile() while the role stays 'client'
 *   source      RegExp of primary source files (counted for package size, grab-bags)
 *   also        RegExp of further code files the walkers read (.mjs, .cjs …), or null
 *   isTest      (posix rel path) → is this a test file, by the toolchain's own naming
 *   comment     'c' (`//`, `/* *\/`) or 'hash' (`#`)
 *   tools       { binary: why } that doctor.mjs checks are on PATH when a stack is enabled
 *   limitConst  optional: RegExp with groups (name, value) for a numeric limit constant
 *   limitName   optional: RegExp source a limit constant's name must match (else the shared constName)
 *   emitCodes   optional: (codes, pkg) → source of the FieldError.code enum (problems-check --emit-codes)
 *   eventArg    server code only: which argument of the event API is the name — 1 after a context
 *               (`obs.Event(ctx, "x.y_created")`), 0 where the context is implicit (`obs.event("x.y_created")`)
 *   defines     server code only: RegExp source of the event API's definition, `{name}` its bare name
 *   eventApi    server code only: the event API when DEV-PROFILE `Event API` is not configured
 *   schema      optional: RegExp of files that define the database schema in this toolchain (an ORM
 *               schema, not a migration); deploy-plan-check treats a change to one as a DB change
 *   routes      optional: RegExp of files that hold HTTP routes or handlers; a change to one with no
 *               contract change is a deploy-plan-check warning, since a request or response shape
 *               may have moved
 *   dataChange  optional: RegExp of this toolchain's calls that rewrite existing rows inside a
 *               migration (an ORM bulk update or delete), beside the SQL statements every adapter shares
 */

const base = (p) => p.slice(p.lastIndexOf('/') + 1);

const go = {
  id: 'go',
  role: 'server',
  stacks: ['go'],
  skill: { go: 'dev-writing-go-code' },
  source: /\.go$/,
  also: null,
  isTest: (p) => p.endsWith('_test.go'),
  comment: 'c',
  eventArg: 1,
  defines: String.raw`func\s+{name}\(`,
  eventApi: 'obs.Event',
  schema: /(^|\/)ent\/schema\/[^/]+\.go$/,
  routes: /(^|\/)(handlers?|routes?|router|api|http)\/[^/]+\.go$/,
  dataChange: null,
  tools: { go: 'stack go', 'golangci-lint': 'stack go (lint gate)' },
  limitConst: /^[ \t]*(?:const[ \t]+)?([A-Za-z_]\w*)(?:[ \t]+[a-z]\w*)?[ \t]*=[ \t]*([\d_][\d_ \t<*+()]*)[ \t]*$/gm,
  limitName: String.raw`^(?:Max[A-Z]\w*|Min[A-Z]\w*|[A-Z]\w*(?:Limit|Cap))$`,
  emitCodes(codes, pkg = 'fielderr') {
    const camel = (c) => c.replace(/(^|_)([a-z0-9])/g, (_, __, ch) => ch.toUpperCase());
    const w = Math.max(...codes.map((c) => camel(c).length)) + 4;
    return [
      '// Code generated by problems-check.mjs --emit-codes from the contract\'s FieldError.code. DO NOT EDIT.',
      '',
      `package ${pkg}`,
      '',
      '// Code is one value of the contract\'s FieldError.code enum.',
      'type Code string',
      '',
      'const (',
      ...codes.map((c) => `\t${`Code${camel(c)}`.padEnd(w)} Code = "${c}"`),
      ')',
      '',
    ].join('\n');
  },
};

const python = {
  id: 'python',
  role: 'server',
  stacks: ['python'],
  skill: { python: 'dev-writing-python-code' },
  source: /\.py$/,
  also: null,
  isTest: (p) => /^test_.*\.py$/.test(base(p)) || /_test\.py$/.test(p) || base(p) === 'conftest.py',
  comment: 'hash',
  eventArg: 0,
  defines: String.raw`def\s+{name}\(`,
  eventApi: 'obs.event',
  schema: null,
  routes: /(^|\/)(routers?|routes?|views|endpoints|api)\/[^/]+\.py$|(^|\/)(views|routes|urls|schemas)\.py$/,
  dataChange: /\bRunPython\b|\bop\.bulk_insert\(|\.objects\.(?:filter\([^)]*\)\.)?(?:update|delete)\(/,
  tools: { uv: 'stack python', ruff: 'stack python (lint gate)' },
  limitConst: /^([A-Z_][A-Z0-9_]*)(?:\s*:\s*(?:int|Final(?:\[int\])?))?\s*=\s*([\d_][\d_ <*+()]*)\s*$/gm,
  emitCodes(codes) {
    return [
      '"""Generated by problems-check.mjs --emit-codes from the contract\'s FieldError.code. Do not edit."""',
      '',
      'from enum import StrEnum',
      '',
      '',
      'class Code(StrEnum):',
      ...codes.map((c) => `    ${c.toUpperCase()} = "${c}"`),
      '',
    ].join('\n');
  },
};

const typescript = {
  id: 'typescript',
  role: 'client',
  stacks: ['react', 'nextjs'],
  skill: { react: 'dev-writing-react-code', nextjs: 'dev-writing-nextjs-code' },
  source: /\.(ts|tsx|js|jsx)$/,
  also: /\.(mjs|cjs|mts|cts)$/,
  isTest: (p) => /\.(test|spec)\.[cm]?[jt]sx?$/.test(base(p)) || (/(^|\/)__tests__\//.test(p) && /\.[cm]?[jt]sx?$/.test(p)),
  comment: 'c',
  // Next.js server code (blueprints/nextjs.md): anything under a `server/` directory, route
  // handlers, server actions, and the root server files. A `.tsx`/`.jsx` file is UI, always;
  // a `.d.ts` declares, it runs nothing.
  isServer: (p, text = '') => !/x$/.test(p) && !/\.d\.ts$/.test(p) && (
    /(^|\/)server\//.test(p)
    || /(^|\/)app\/(?:.*\/)?route\.[cm]?[jt]s$/.test(p)
    || /(^|\/)(?:actions|server-entry|proxy|middleware|instrumentation)\.[cm]?[jt]s$/.test(p)
    || /^(?:\s|\/\/[^\n]*\n|\/\*[\s\S]*?\*\/)*['"]use server['"]/.test(text)),
  eventArg: 0,
  defines: String.raw`(?:function\s+{name}\s*[(<]|(?:const|let)\s+{name}\s*=)`,
  eventApi: 'obs.event',
  schema: /(^|\/)schema\.prisma$|(^|\/)(db|drizzle)\/schema(\/[^/]+)?\.[cm]?[jt]s$/,
  routes: /(^|\/)app\/(?:.*\/)?route\.[cm]?[jt]s$|(^|\/)pages\/api\/|(^|\/)server\/(routes?|routers?|handlers?)\/[^/]+\.[cm]?[jt]s$/,
  dataChange: /\.(?:updateMany|deleteMany)\(|\bknex\([^)]*\)\.(?:update|del|delete)\(/,
  tools: { npm: 'stack react/nextjs' },
  limitConst: /^\s*(?:export\s+)?(?:const|let|var)\s+([A-Za-z_]\w*)(?:\s*:\s*number)?\s*=\s*([\d_][\d_ <*+()]*)\s*;?\s*$/gm,
};

/** Every adapter, in the order checkers report them. */
export const LANGS = [go, python, typescript];

/** DEV-PROFILE §Stacks keys that are not a programming language of their own. */
export const NON_CODE_STACKS = ['sql'];

const byId = new Map(LANGS.map((l) => [l.id, l]));
const ext = (re) => re.source.replace(/^\\\.\(?|\)?\$$/g, '');

/** Every file any checker treats as code, built from the adapters. */
export const CODE_EXT = new RegExp(`\\.(${LANGS.flatMap((l) => [l.source, l.also].filter(Boolean).map(ext)).join('|')})$`);
/**
 * Extensions of the server-role languages (every file of theirs is backend code). Not the whole
 * backend: a client language's server files are found by isServerFile(), which the problem, limit
 * and observability checks use. conventions-check still reads by extension.
 */
export const SERVER_EXT = new RegExp(`\\.(${LANGS.filter((l) => l.role === 'server').map((l) => ext(l.source)).join('|')})$`);

/** Primary source only (no .mjs/.cjs tooling files). */
export const SOURCE_EXT = new RegExp(`\\.(${LANGS.map((l) => ext(l.source)).join('|')})$`);

const posix = (p) => String(p).replace(/\\/g, '/');

/** The adapter for a path, or null when no adapter claims it. */
export function langOf(path) {
  const p = posix(path);
  return LANGS.find((l) => l.source.test(p) || l.also?.test(p)) ?? null;
}

export const lang = (id) => byId.get(id) ?? null;

/**
 * Backend code: a file of a server-role language, or a file a client language's `isServer` claims
 * (Next.js `src/server/`, `app/.../route.ts`, `actions.ts`, `proxy.ts`, a `'use server'` module).
 * `text`, when given, lets a file opt in by its directive. Tests are not filtered here.
 */
export function isServerFile(path, text) {
  const p = posix(path);
  const l = langOf(p);
  if (!l) return false;
  return l.role === 'server' || !!l.isServer?.(p, text);
}

/** A test file, by the naming its own toolchain uses. */
export function isTestFile(path) {
  const p = posix(path);
  return LANGS.some((l) => l.isTest(p));
}

/**
 * A test file or anything under a test directory (`tests/`, `test/`, `__tests__/`). The source
 * checkers (limits, problems, observability, privacy) use this wider net: a constant in a fixture
 * module is not a product limit, whatever the file is called.
 */
export function isTestPath(path) {
  const p = posix(path);
  return isTestFile(p) || /(^|\/)(tests?|__tests__)\//.test(p) || /(^|\/)[^/]*_test\.py$/.test(p) || /\.(test|spec)\.[jt]sx?$/.test(p);
}

/** A file an adapter names as the database schema (an ORM schema, not a migration). */
export function isSchemaFile(path) {
  const p = posix(path);
  return LANGS.some((l) => l.schema?.test(p));
}

/** A file an adapter names as holding HTTP routes or handlers. Tests are never routes. */
export function isRouteFile(path) {
  const p = posix(path);
  return !isTestPath(p) && LANGS.some((l) => l.routes?.test(p));
}

/** The first ORM call in `text` that rewrites existing rows, by the adapter of `path`, or null. */
export function dataChangeCall(path, text) {
  const re = langOf(path)?.dataChange;
  return re ? (String(text ?? '').match(re)?.[0] ?? null) : null;
}

/** The comment style of a path: 'py' for `#` languages, 'c' otherwise (blankComments' vocabulary). */
export function commentStyle(path) {
  return langOf(path)?.comment === 'hash' ? 'py' : 'c';
}

/** The adapter serving a DEV-PROFILE stack key, or null (sql, or an unknown key). */
export function langOfStack(key) {
  return LANGS.find((l) => l.stacks.includes(key)) ?? null;
}

/** Every stack key the registry knows, code or not. */
export const STACK_KEYS = [...LANGS.flatMap((l) => l.stacks), ...NON_CODE_STACKS];

/** { binary: why } for the enabled stacks: what doctor.mjs checks is on PATH. */
export function toolsFor(stacks) {
  const need = new Map();
  for (const s of stacks) for (const [bin, why] of Object.entries(langOfStack(s)?.tools ?? {})) need.set(bin, why);
  return need;
}
